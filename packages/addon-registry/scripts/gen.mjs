// addons:gen: build-time add-on discovery (ADDON-01, ADDON-10; CONTEXT A1-Q1, RESEARCH
// Pattern 1, Pitfall 10; invariant 4).
//
// Lists packages/addons/*/package.json and writes static-import barrels into
// packages/addon-registry/src/generated/: manifests (pure), server, site and admin (one per
// entry point, so server code never reaches a client bundle), plus howto.ts, which bakes the
// "Use" steps of every docs/how-to/addon-*.md so training renders in the standalone bundle
// without docs/. 11-46 (DASH-17): help.ts bakes every docs/how-to/*.md (except TEMPLATE.md and
// README.md): front matter, a one-line summary and the Activate and Use steps, so the Help
// center renders in the standalone image without docs/. It is a separate file (and the
// server-side `@cds/addon-registry/help` entry) so the client builder bundle, which imports
// howto.ts through the pure entry, does not carry every how-to. Dropping a folder into packages/addons and running `npm run addons:gen` is
// the only step to register an add-on. The generated files are committed; a drift test
// (test/generated.test.ts) fails when they are stale.
//
// `--check` (npm run addons:check) writes nothing and exits 1 when any committed file is
// stale. The gates run the check; only dev (addons:gen, predev) writes (B-CR-02).
//
// render() is pure; the CLI at the bottom is a thin writer.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const HEADER = "// GENERATED by npm run addons:gen. Do not edit.";
const PREFIX = "@cds/addon-";
const SLUG = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

export const DEFAULT_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "..",
  "..",
);

/** Sorted add-on folders under packages/addons that hold a package.json. */
export function discover(repoRoot = DEFAULT_ROOT) {
  const dir = path.join(repoRoot, "packages", "addons");
  if (!existsSync(dir)) return [];
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const pkgPath = path.join(dir, entry.name, "package.json");
    if (!existsSync(pkgPath)) continue;
    const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
    const slug = entry.name;
    if (!SLUG.test(slug)) {
      throw new Error(`add-on folder "${slug}" is not a valid slug`);
    }
    if (pkg.name !== PREFIX + slug) {
      throw new Error(
        `packages/addons/${slug}/package.json name must be "${PREFIX}${slug}", got "${pkg.name}"`,
      );
    }
    out.push({ slug, name: pkg.name });
  }
  return out.sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));
}

/**
 * Add-on training how-tos that are not named addon-*.md (10-42: the Pro table has its own
 * recording script, docs/how-to/pro-table.md, used by Builder Pro's training).
 */
export const EXTRA_ADDON_HOWTOS = Object.freeze(["pro-table.md"]);

/** docs/how-to/addon-*.md (+ EXTRA_ADDON_HOWTOS) only: core how-to edits never touch generated files. */
export function readHowtos(repoRoot = DEFAULT_ROOT) {
  const dir = path.join(repoRoot, "docs", "how-to");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter(
      (f) => /^addon-[a-z0-9-]+\.md$/.test(f) || EXTRA_ADDON_HOWTOS.includes(f),
    )
    .sort()
    .map((f) => ({
      path: `docs/how-to/${f}`,
      text: readFileSync(path.join(dir, f), "utf8"),
    }));
}

/** Every how-to except the template and the folder README (11-46, Help center). */
export const HELP_SKIP = Object.freeze(["TEMPLATE.md", "README.md"]);

/**
 * Staff and operator how-tos: their front-matter `route` is a terminal tool, CLI, API,
 * Coolify setting, a staff console screen (`/staff...`, P13) or the monitor endpoint
 * (`/api/monitor...`). They are never baked for Help, so staff procedures can't reach a
 * tenant even by id (T-11-45-01, T-13-01-01; defence in depth: they have no training entry).
 */
export const STAFF_ROUTE =
  /^(terminal\b|CLI\b|API\b|npm run\b|Coolify\b|\/staff\b|\/api\/monitor\b)/i;

/** Staff console how-tos (13-01, P13-P12): baked into staff-help.ts for the console "?". */
export const CONSOLE_ROUTE = /^\/staff\b/i;

export function isStaffHowto(text) {
  return STAFF_ROUTE.test(parseFrontMatter(text).route ?? "");
}

export function isConsoleHowto(text) {
  return CONSOLE_ROUTE.test(parseFrontMatter(text).route ?? "");
}

/**
 * Pure: split how-tos ({ path, text }) into the tenant Help set (never a staff how-to) and
 * the staff console set (route starts /staff). Operator how-tos (terminal, CLI, monitor)
 * land in neither.
 */
export function partitionHowtos(items) {
  const help = [];
  const staff = [];
  for (const h of items) {
    if (!isStaffHowto(h.text)) help.push(h);
    else if (isConsoleHowto(h.text)) staff.push(h);
  }
  return { help, staff };
}

function readAllHowtos(repoRoot) {
  const dir = path.join(repoRoot, "docs", "how-to");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".md") && !HELP_SKIP.includes(f))
    .sort()
    .map((f) => ({
      path: `docs/how-to/${f}`,
      text: readFileSync(path.join(dir, f), "utf8"),
    }));
}

/** docs/how-to/*.md minus HELP_SKIP and staff how-tos, for help.ts (11-46). */
export function readHelpHowtos(repoRoot = DEFAULT_ROOT) {
  return partitionHowtos(readAllHowtos(repoRoot)).help;
}

/** docs/how-to/*.md whose route starts /staff, for staff-help.ts (13-01, P13-P12). */
export function readStaffHowtos(repoRoot = DEFAULT_ROOT) {
  return partitionHowtos(readAllHowtos(repoRoot)).staff;
}

/** docs/runbooks/*.md (the directory may not exist yet). */
export function readRunbooks(repoRoot = DEFAULT_ROOT) {
  const dir = path.join(repoRoot, "docs", "runbooks");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => `docs/runbooks/${f}`);
}

function cells(row) {
  return row
    .trim()
    .replace(/^\|/, "")
    .replace(/\|$/, "")
    .split("|")
    .map((c) => c.trim());
}

/** The rows of the step table under `## <heading>` (same table shape as tests/howto.test.ts). */
export function parseStepTable(md, heading) {
  const parts = md.replace(/\r\n/g, "\n").split(/^## /m);
  const sec = parts
    .slice(1)
    .find((p) => p.slice(0, p.indexOf("\n")).trim() === heading);
  if (!sec) return [];
  const lines = sec.split("\n");
  const start = lines.findIndex((l) => l.trim().startsWith("|"));
  if (start === -1) return [];
  const table = [];
  for (const l of lines.slice(start)) {
    if (!l.trim().startsWith("|")) break;
    table.push(l);
  }
  const [head, sep, ...rows] = table;
  const header = cells(head);
  if (
    !sep ||
    !/^[\s|:-]+$/.test(sep) ||
    header.join("|") !== "#|Screen / route|Action|Expected result"
  ) {
    return [];
  }
  return rows.map((r) => {
    const [, screen = "", action = "", expected = ""] = cells(r);
    return { screen, action, expected };
  });
}

/** The "## Use" table rows. */
export function parseUseSteps(md) {
  return parseStepTable(md, "Use");
}

/** `key: value` lines of the leading `---` front matter block. */
export function parseFrontMatter(md) {
  const text = md.replace(/\r\n/g, "\n");
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  const out = {};
  if (!m) return out;
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i <= 0) continue;
    out[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return out;
}

/** The `# How to: X` title (or the first `# ` heading), else the front-matter feature. */
export function parseTitle(md) {
  const text = md.replace(/\r\n/g, "\n").replace(/^---\n[\s\S]*?\n---\n/, "");
  const m = /^# (?:How to: )?(.+)$/m.exec(text);
  return (m?.[1] ?? parseFrontMatter(md).feature ?? "").trim();
}

/** Markdown inline marks to plain text (links keep their label). */
export function plainText(s) {
  return (
    s
      .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
      .replace(/\*\*([^*]+)\*\*/g, "$1")
      .replace(/`([^`]*)`/g, "$1")
      // Requirement and decision refs ("(CONT-28, D235)") mean nothing to an owner.
      .replace(/\s*\((?:[A-Z]+-\d+|D\d+)[^)]*\)/g, "")
      .replace(/\s+/g, " ")
      .trim()
  );
}

/** Boilerplate paragraphs that never make a summary. */
const SUMMARY_SKIP = [
  /^These steps are the recording script/,
  /^Operator feature/,
  /^\*\*Staff only/,
  /^Owner-hub steps use/,
  /^Final steps against/,
];

export const SUMMARY_MAX = 160;

/**
 * One line for the Help center row: the first sentence of the first prose paragraph after
 * the title (boilerplate skipped), plain text, cut at a word under SUMMARY_MAX characters.
 */
export function parseSummary(md) {
  const text = md.replace(/\r\n/g, "\n").replace(/^---\n[\s\S]*?\n---\n/, "");
  const body = text.split(/^## /m)[0];
  for (const para of body.split(/\n\s*\n/)) {
    const p = para.trim();
    if (!p || /^[#|>-]/.test(p)) continue;
    if (SUMMARY_SKIP.some((re) => re.test(p))) continue;
    const plain = plainText(p);
    // A sentence ends before a capital or an opening quote ("the ? beside" is not an end).
    const first = /^.+?[.!?](?=\s+[A-Z"“]|$)/.exec(plain)?.[0] ?? plain;
    if (first.length <= SUMMARY_MAX) return first;
    const cut = first.slice(0, SUMMARY_MAX - 1);
    return cut.slice(0, cut.lastIndexOf(" ")).replace(/[,;:]$/, "") + "…";
  }
  return "";
}

function ident(slug) {
  return "addon_" + slug.replace(/-/g, "_");
}

function moduleMap(addons, subpath, constName) {
  const lines = [HEADER];
  if (addons.length === 0) {
    lines.push(
      "",
      `export const ${constName}: Readonly<Record<string, never>> = Object.freeze({});`,
    );
    return lines.join("\n") + "\n";
  }
  for (const a of addons) {
    lines.push(`import * as ${ident(a.slug)} from "${a.name}/${subpath}";`);
  }
  lines.push("", `export const ${constName} = Object.freeze({`);
  for (const a of addons)
    lines.push(`  ${JSON.stringify(a.slug)}: ${ident(a.slug)},`);
  lines.push("});");
  return lines.join("\n") + "\n";
}

/**
 * Pure: generated file contents keyed by path relative to packages/addon-registry.
 * input = { addons: [{ slug, name }], howtos: [{ path, text }], runbooks: [path],
 *           helpHowtos?: [{ path, text }], staffHowtos?: [{ path, text }] }
 */
export function render({
  addons,
  howtos,
  runbooks,
  helpHowtos = [],
  staffHowtos = [],
}) {
  const sorted = [...addons].sort((a, b) =>
    a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0,
  );

  const manifests = [
    HEADER,
    'import type { AddonManifest } from "@cds/core/addons";',
  ];
  for (const a of sorted)
    manifests.push(`import ${ident(a.slug)} from "${a.name}";`);
  manifests.push(
    "",
    `export const MANIFESTS: readonly AddonManifest[] = Object.freeze([${sorted
      .map((a) => ident(a.slug))
      .join(", ")}]);`,
  );

  const steps = {};
  for (const h of [...howtos].sort((a, b) => (a.path < b.path ? -1 : 1))) {
    steps[h.path] = parseUseSteps(h.text);
  }
  const howto = [
    HEADER,
    "",
    "export type HowToStep = { screen: string; action: string; expected: string };",
    "",
    "export const HOWTO_STEPS: Readonly<Record<string, readonly HowToStep[]>> = Object.freeze(",
    `  ${JSON.stringify(steps, null, 2).replace(/\n/g, "\n  ")},`,
    ");",
    "",
    `export const RUNBOOKS: readonly string[] = Object.freeze(${JSON.stringify([...runbooks].sort())});`,
  ];

  const articles = {};
  for (const h of [...helpHowtos].sort((a, b) => (a.path < b.path ? -1 : 1))) {
    const fm = parseFrontMatter(h.text);
    articles[h.path] = {
      feature: fm.feature ?? "",
      route: fm.route ?? "",
      summary: parseSummary(h.text),
      activate: parseStepTable(h.text, "Activate"),
      use: parseStepTable(h.text, "Use"),
    };
  }
  const help = [
    HEADER,
    "// Server-side Help center data (11-46): every docs/how-to/*.md except TEMPLATE and README.",
    "",
    'import type { HowToStep } from "./howto";',
    "",
    "export type HelpArticleData = {",
    "  feature: string;",
    "  route: string;",
    "  summary: string;",
    "  activate: readonly HowToStep[];",
    "  use: readonly HowToStep[];",
    "};",
    "",
    "export const HELP_ARTICLES: Readonly<Record<string, HelpArticleData>> = Object.freeze(",
    `  ${JSON.stringify(articles, null, 2).replace(/\n/g, "\n  ")},`,
    ");",
  ];

  const staffArticles = {};
  for (const h of [...staffHowtos].sort((a, b) => (a.path < b.path ? -1 : 1))) {
    const fm = parseFrontMatter(h.text);
    staffArticles[path.posix.basename(h.path, ".md")] = {
      title: parseTitle(h.text),
      route: fm.route ?? "",
      activate: parseStepTable(h.text, "Activate"),
      use: parseStepTable(h.text, "Use"),
    };
  }
  const staffHelp = [
    HEADER,
    "// Staff console only (13-01, P13-P12): how-tos whose route starts /staff, keyed by slug.",
    "// Imported only by /staff pages; never by the tenant Help center or a client component.",
    "",
    'import type { HowToStep } from "./howto";',
    "",
    "export type StaffHelpArticle = {",
    "  title: string;",
    "  route: string;",
    "  activate: readonly HowToStep[];",
    "  use: readonly HowToStep[];",
    "};",
    "",
    "export const STAFF_HELP: Readonly<Record<string, StaffHelpArticle>> = Object.freeze(",
    `  ${JSON.stringify(staffArticles, null, 2).replace(/\n/g, "\n  ")},`,
    ");",
  ];

  return {
    "src/generated/manifests.ts": manifests.join("\n") + "\n",
    "src/generated/server.ts": moduleMap(sorted, "server", "SERVER_MODULES"),
    "src/generated/site.ts": moduleMap(sorted, "site", "SITE_MODULES"),
    "src/generated/admin.ts": moduleMap(sorted, "admin", "ADMIN_MODULES"),
    "src/generated/howto.ts": howto.join("\n") + "\n",
    "src/generated/help.ts": help.join("\n") + "\n",
    "src/generated/staff-help.ts": staffHelp.join("\n") + "\n",
  };
}

/** Everything render() needs, read from disk. */
export function collect(repoRoot = DEFAULT_ROOT) {
  return {
    addons: discover(repoRoot),
    howtos: readHowtos(repoRoot),
    runbooks: readRunbooks(repoRoot),
    helpHowtos: readHelpHowtos(repoRoot),
    staffHowtos: readStaffHowtos(repoRoot),
  };
}

const isMain =
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

/**
 * Pure: generated paths whose on-disk content differs from `files` (B-CR-02).
 * `read(rel)` returns the committed text, or null when the file is missing.
 */
export function staleFiles(files, read) {
  const stale = [];
  for (const [rel, content] of Object.entries(files)) {
    const onDisk = read(rel);
    if (onDisk === null || onDisk.replace(/\r\n/g, "\n") !== content) {
      stale.push(rel);
    }
  }
  return stale;
}

if (isMain && process.argv.includes("--check")) {
  // The gates (pretypecheck, pretest, prebuild, CI) only check: they never rewrite the
  // barrels, so the committed files are what CI tests and what the image ships.
  const pkgDir = path.join(DEFAULT_ROOT, "packages", "addon-registry");
  const stale = staleFiles(render(collect(DEFAULT_ROOT)), (rel) => {
    const file = path.join(pkgDir, rel);
    return existsSync(file) ? readFileSync(file, "utf8") : null;
  });
  if (stale.length > 0) {
    console.error(
      `add-on barrels are stale: ${stale
        .map((r) => `packages/addon-registry/${r}`)
        .join(", ")}\nRun npm run addons:gen and commit the output.`,
    );
    process.exit(1);
  }
  console.log("add-on barrels are current");
} else if (isMain) {
  const pkgDir = path.join(DEFAULT_ROOT, "packages", "addon-registry");
  const files = render(collect(DEFAULT_ROOT));
  let n = 0;
  for (const [rel, content] of Object.entries(files)) {
    writeFileSync(path.join(pkgDir, rel), content);
    n++;
  }
  console.log(`wrote ${n} files`);
}
