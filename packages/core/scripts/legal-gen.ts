// legal:gen: compile the CDS signup policies and the e-sign consent text into a committed TS
// module (AGR-01, AGR-07; RESEARCH Pattern 1, Pitfall 3: markdown is not traced into the
// standalone image, so runtime code reads only the generated module).
//
// Sources: packages/core/src/legal/policies/<key>/v<N>.md and
// packages/core/src/legal/esign-consent/v<N>.md (front matter + restricted legal markdown).
// Output: packages/core/src/legal/policies.generated.ts.
//
// 09-11 (AGR-08, D217): tenant site policy templates, site-policies/<page>/v<N>.md (page
// privacy | terms), compile into src/legal/site-policies.generated.ts (SITE_POLICY_TEMPLATES).
// Their tenant {{vars}} stay in the body (filled at render by renderSitePolicy); privacy holds
// exactly one full-line {{clauses}} slot, terms none; every version N exists for both pages.
//
// Hash = sha256(utf8(canonical body)); canonical = BOM stripped, CRLF/CR -> LF, NFC,
// trailing whitespace trimmed per line, exactly one final "\n", after {{var}} substitution,
// clause markers kept (they are authored text; only the HTML drops them).
//
// compileLegalSources() is pure over in-memory sources; render() reads files; the CLI at the
// bottom writes by default, and `--check` (npm run legal:check, run by pretypecheck, pretest,
// prebuild and the Docker build) writes nothing and exits 1 on drift.
//
// CR-B01: src/legal/policies.lock.json pins every published version's sha256. legal:gen adds
// new versions to it; both gen and check fail if a locked version's text changes or vanishes.
//
// Run: node --experimental-strip-types --no-warnings=ExperimentalWarning \
//        --import ./packages/db/scripts/register-ts.mjs packages/core/scripts/legal-gen.ts [--check]
